const go = (id: string) => {
  const el = document.getElementById(id);
  if (!el) return;
  el.scrollIntoView({ behavior: 'smooth', block: 'start' });
  history.replaceState(null, '', '#' + id);
};

function Toc({ mobile }: { mobile?: boolean }) {
  const list = (
    <ol className="guide-toc-list">
      {SECTIONS.map(([id, t], i) => <li key={id}><button type="button" onClick={() => go(id)}><span className="mono">{i + 1}</span>{t}</button></li>)}
    </ol>
  );
  return mobile
    ? <details className="guide-toc mobile"><summary>Зміст</summary>{list}</details>
    : <nav className="guide-toc" aria-label="Зміст інструкції"><h2>Зміст</h2>{list}</nav>;
}

