/* Рядок, схожий на запис в облік («500к зарплата», «продав 20 гливи по 300»), — після 0.6 облік прибрано (specs/040),
   тож плашка відповідає сама й не витрачає на нього ліміт ШІ. Питання («скільки дає скупник за гливу?», «чи можна 500к штраф?»)
   — не запис: їх шукаємо в правилах чи питаємо ШІ, як і раніше. */
const DEAL = /^\s*(про?дав|продала|купи(в|ла)|скупи(в|ла)|прикупи(в|ла)|(на)?фарми(в|ла)|зібра(в|ла)|здав|здала|поклав|поклала|зня(в|ла)|переказа(в|ла)|витрати(в|ла)|заробив|заробила|отрима(в|ла))(?=\s|$)/i;   // не \b: у JS він лише для латиниці
const MONEY = /(^|[\s+−-])\d[\d\s.,]*\s?(кк|к|kk|k|\$|грн)?(?=\s|$)/i;
const QUESTION = /\?|(^|\s)(скільки|чи|як|що|де|коли|чому|навіщо|який|яка|яке|які|можна|ціна|ціну|ціни|правил\p{L}*|закон\p{L}*|штраф\p{L}*)(\s|$)/iu;

export function isRecordLike(text: string): boolean {
  const t = text.trim();
  if (!t || QUESTION.test(t)) return false;
  if (DEAL.test(t)) return true;
  const m = MONEY.exec(t);
  if (!m) return false;
  /* «500к», «+30000», «12 000 $» — сума з позначкою чи від 1000; номер статті «6.5» — ні */
  const raw = m[0].trim(), hasUnit = /(кк|к|kk|k|\$|грн)$/i.test(raw), n = Number(raw.replace(/[^\d]/g, ''));
  return hasUnit || n >= 1000;
}

