import { describe, expect, it } from 'vitest';
import { placesText, rulesText, ruleText, splitPenalty } from './barParts';

const h = { topic: 'Кримінальний кодекс штату Quant', url: '', kind: 'law' as const, n: '6.5', h: '', score: 1, s: 'Вимагання грошей | Позбавлення волі 30 хв. Примітка: лише для ПД' };

describe('текст для «Копіювати»', () => {
  it('пункт: джерело з номером, текст, покарання, примітка', () => {
    expect(ruleText(h)).toBe('Кримінальний кодекс штату Quant, ст. 6.5\nВимагання грошей\nПозбавлення волі 30 хв.\nПримітка: лише для ПД');
  });
  it('без номера й покарання', () => {
    expect(ruleText({ ...h, kind: 'rules', n: '', s: 'Заборонено DM' })).toBe('Кримінальний кодекс штату Quant\nЗаборонено DM');
  });
  it('усі пункти — через порожній рядок', () => {
    expect(rulesText([h, h]).split('\n\n')).toHaveLength(2);
  });
  it('місця з координатами', () => {
    expect(placesText([{ id: '1', name: 'Заправка №3', cat: 'Заправки', icon: '', x: 120.4, y: -339.6 }])).toBe('Заправка №3 — Заправки, X 120 · Y -340');
  });
});

/* specs/085: у законах штату покарання — окремими рядками «Пріоритет розшуку» / «Карається», без « | » */
describe('splitPenalty — закони штату', () => {
  const s = '[Р] Втеча з місця злочину.\nПріоритет розшуку: 3.\nКарається позбавленням волі терміном до 30 місяців або кримінальним штрафом у розмірі 60.000$.';
  it('рядки розшуку й кари — у покарання, текст статті окремо', () => {
    expect(splitPenalty(s)).toEqual({ body: '[Р] Втеча з місця злочину.', pen: 'Пріоритет розшуку: 3 · Карається позбавленням волі терміном до 30 місяців або кримінальним штрафом у розмірі 60.000$.', more: '' });
  });
  it('лише «Карається» без розшуку', () => {
    expect(splitPenalty('Текст статті.\nКарається штрафом 5.000$.')).toEqual({ body: 'Текст статті.', pen: 'Карається штрафом 5.000$.', more: '' });
  });
  it('без рядків покарання й без « | » — як було', () => {
    expect(splitPenalty('Просто текст\nз переносом')).toEqual({ body: 'Просто текст\nз переносом', pen: '', more: '' });
  });
  it('« | » (правила сервера) — як було', () => {
    expect(splitPenalty('Заборонено DM | Деморган 60 хвилин')).toEqual({ body: 'Заборонено DM', pen: 'Деморган 60 хвилин', more: '' });
  });
});
