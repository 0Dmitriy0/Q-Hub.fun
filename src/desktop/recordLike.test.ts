import { describe, expect, it } from 'vitest';
import { isRecordLike } from './recordLike';

describe('рядок-запис після 0.6 (specs/040)', () => {
  it('записи — плашка відповідає сама, без ШІ', () => {
    for (const t of ['500к зарплата', '+30000 робота', 'продав 20 гливи по 300', 'купив ремкомплект 2500', 'нафармив 47 колод',
      'зняв 200к з картки', '12 000 $ податок', '1,5кк машина']) expect(isRecordLike(t), t).toBe(true);
  });
  it('питання й пошук — як раніше (правила чи ШІ)', () => {
    for (const t of ['скільки дає скупник за гливу', 'чи можна 500к штраф?', 'зелена зона', 'ст. 6.5', 'капт 15 людей',
      'де заправка', 'ціна гливи 300', 'DM в зеленій зоні', '']) expect(isRecordLike(t), t).toBe(false);
  });
});
