import { describe, expect, it } from 'vitest';
import { hourlyRates, hourlyTop, shortK } from './payHourly';

describe('заробіток за годину з тексту', () => {
  it('діапазон і рівень', () => {
    expect(hourlyRates('≈80 000–100 000$ чистими за годину на 1 рівні навички.')).toEqual([{ label: '1 рівень', min: 80000, max: 100000 }]);
  });
  it('кілька рядків: культура й вимір таймером', () => {
    const r = hourlyRates('Апельсини — ≈150 000$ за годину (≈1 200 штук). Молоко — ≈80 000$ за годину (≈70 пляшок).');
    expect(r).toEqual([{ label: 'Апельсини', min: 150000, max: 150000 }, { label: 'Молоко', min: 80000, max: 80000 }]);
    expect(hourlyRates('≈50 000–75 000$ за годину на старті. · Рівень 1: ≈132 200 $/год (вимір 58 хв)')).toEqual([
      { label: '', min: 50000, max: 75000 }, { label: '1 рівень', min: 132200, max: 132200 }]);
  });
  it('без годинного заробітку — порожньо; дрібні суми не беремо', () => {
    expect(hourlyRates('Залежить від відстані, від однієї мітки - до іншої.')).toEqual([]);
    expect(hourlyRates('≈6 000–8 000$ за одне відвезене авто.')).toEqual([]);
    expect(hourlyRates('продаж ≈12$ за годину')).toEqual([]);
  });
  it('легально й нелегально', () => {
    expect(hourlyRates('≈90 000$ за годину легально')[0]).toEqual({ label: 'легально', min: 90000, max: 90000 });
  });
  it('найбільше значення й коротка форма', () => {
    expect(hourlyTop('≈15 000$ за авто і ≈120 000$ за годину на 2 рівні')).toBe(120000);
    expect(shortK(50000, 75000)).toBe('≈50–75 тис.');
    expect(shortK(120000, 120000)).toBe('≈120 тис.');
    expect(shortK(900000, 1200000)).toBe('≈900 тис.–1.2 млн');
  });
});
