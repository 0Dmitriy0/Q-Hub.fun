/* Логотип Q-Hub з назвою на самій мапі — у порожньому місці під «ГОРА ЧІЛІАД» (рішення власника 2026-11-16).
   Квадрат у метрах гри, тож на мапі сайту, у програмі й на мінікарті гри він росте й меншає разом із місцевістю. */
export const BRAND_SRC = '/brand/q-hub-map.svg';
/* центр і сторона квадрата (м); напис «ЧІЛІАД» — на y ≈ 5537, квадрат одразу під ним */
export const BRAND_SPOT = { x: 770, y: 5260, size: 420 };

/* кути квадрата: лівий верхній і правий нижній (y гри росте вгору) */
export function brandBox(s = BRAND_SPOT): { x0: number; y0: number; x1: number; y1: number } {
  const h = s.size / 2;
  return { x0: s.x - h, y0: s.y + h, x1: s.x + h, y1: s.y - h };
}
