import { describe, expect, it } from 'vitest';
import { days, kyivDay, phase, range, upcoming } from './seasons';

describe('сезонні івенти й промокоди', () => {
  it('день за Києвом, а не за UTC', () => {
    expect(kyivDay(Date.UTC(2026, 9, 26, 22, 30))).toBe('2026-10-27');   // 00:30 у Києві
    expect(kyivDay(Date.UTC(2026, 9, 27, 12))).toBe('2026-10-27');
  });
  it('фаза: скоро, триває (кінець включно), минув', () => {
    expect(phase('2026-10-30', '2026-11-02', '2026-10-27')).toEqual({ kind: 'soon', in: 3 });
    expect(phase('2026-10-25', '2026-11-02', '2026-10-27')).toEqual({ kind: 'now', left: 7 });
    expect(phase('2026-10-25', '2026-10-27', '2026-10-27')).toEqual({ kind: 'now', left: 1 });
    expect(phase('2026-10-01', '2026-10-26', '2026-10-27')).toEqual({ kind: 'past' });
  });
  it('дати коротко, рік — лише не поточний', () => {
    expect(range('2026-10-27', '2026-11-02', '2026-10-27')).toBe('27.10–02.11');
    expect(range('2026-12-30', '2027-01-05', '2026-10-27')).toBe('30.12–05.01.2027');
    expect(range('2026-10-31', '2026-10-31', '2026-10-27')).toBe('31.10');
  });
  it('відміна «днів»', () => {
    expect([1, 2, 5, 11, 21, 22, 25].map(days)).toEqual(['1 день', '2 дні', '5 днів', '11 днів', '21 день', '22 дні', '25 днів']);
  });
  it('порядок: що скоро закінчиться — першим, далі майбутні; минулих немає', () => {
    const r = upcoming([
      { id: 1, starts_on: '2026-10-20', ends_on: '2026-11-10' },
      { id: 2, starts_on: '2026-10-25', ends_on: '2026-10-28' },
      { id: 3, starts_on: '2026-11-01', ends_on: '2026-11-03' },
      { id: 4, starts_on: '2026-10-01', ends_on: '2026-10-02' },
    ], '2026-10-27');
    expect(r.map(x => x.id)).toEqual([2, 1, 3]);
  });
});
