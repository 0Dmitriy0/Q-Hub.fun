/* «Зір» програми: де гравець — магазин 24/7, скупник, банкомат… Поки HUD закритий меню, програма читає текст екрана (OCR)
   і впізнає місце; для цін скупників це сигнал, що відкрите його вікно. Облік за місцем програма більше не веде (specs/040).
   Чиста логіка — перевіряється scene.test.cjs. */

const low = s => String(s || '').toLowerCase().replace(/\s+/g, ' ');

/* текст меню → місце. Порядок важливий: «Купує … Продати» — скупник, навіть якщо десь видно слово «магазин» */
const RULES = [
  /* «Риба» 2026-10-29: OCR дав «Kynye» замість «Купує», «Продам | $159» замість «Продати $159», «ліміт продажу» не дочитав,
     а ціни там «за кг» — тож і латинський двійник, і кілька кнопок «Продати $…» (одна — ще не скупник) */
  ['buyer', /купу[єеє]\s|kynye|продати все|за (шт|кг)\b|ліміт продажу|(прода[тм]\S*\s*\|?\s*\$\s?\d[\s\S]*){2}/, t => { const m = t.match(/купу[єе]\s+([\p{L}' ]{3,20})/u); return 'Скупник' + (m ? ': ' + m[1].trim().split(' ')[0] : ''); }],
  ['shop', /магазин\s*24\s*\/?\s*7/, t => { const m = t.match(/магазин\s*24\s*\/?\s*7\s*#?\s*(\d+)/); return 'Магазин 24/7' + (m ? ' #' + m[1] : ''); }],
  ['bank', /mazebank|maze bank|банкомат|поповнити|баланс на рахунку|fleeca/, () => 'Банкомат'],
  ['market', /маркетплейс|marketplace|торговий майданчик/, () => 'Маркетплейс'],
  ['fuel', /заправк|азс|пальне|бензин|літр/, () => 'Заправка'],
  ['tune', /тюнінг|customs|ls customs|покраск/, () => 'Тюнінг'],
  ['clothes', /одяг|binco|suburban|ponsonbys|магазин одягу/, () => 'Магазин одягу'],
  ['license', /ліценз|license/, () => 'Ліцензії'],
];
function scene(text) {
  const t = low(text);
  for (const [kind, re, title] of RULES) if (re.test(t)) return { kind, title: title(t) };
  return null;
}

module.exports = { scene };
