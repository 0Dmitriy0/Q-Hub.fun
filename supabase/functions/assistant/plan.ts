/* ШІ-помічник програми (Alt+Q): з тексту гравця, пунктів правил і цін скупників — коротка відповідь.
   Тут немає ні Deno, ні мережі: функція (index.ts) лише збирає дані й кличе модель, а це — промпт і схема відповіді.
   Облік, угоди й склад прибрано (specs/040): помічник нічого не записує і не бачить грошей гравця. */

export interface PriceIn { buyer: string; item: string; price: number; min: number; max: number }
export interface Ctx { prices: PriceIn[] }
export interface Plan { reply: string; actions: [] }

