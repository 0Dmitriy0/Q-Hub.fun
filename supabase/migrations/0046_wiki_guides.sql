Етап: Перші гроші

Роботи з 1 рівня персонажа, доступні всім: Водій автобуса, Кур'єр, Поштар, Сміттяр, Водій навантажувача, Механік. Знайти їх: Телефон → GPS → Роботи (або Робота).

Біля роботи підійди до роботодавця, поговори з ним і натисни [Влаштуватися].

Заробіток без роботодавця з 1 рівня — Грибник, Лісоруб, Каменяр, Рибак, Шукач мотлоху: Телефон → GPS → Заробіток. Зібране продаєш скупникам.

Усі роботи з рівнем, оплатою й точкою на мапі — у WIKI: /wiki/roboty

Етап: Правила, які треба знати одразу

Важливо: у Зелених зонах (мерія, LSPD, BCSD, EMS, порт, початкові точки появи та інші) заборонено шкодити гравцям, грабувати й викрадати. Зелені зони видно на мапі Q-Hub: /mapa

Дії відіграються командами: /me — з маленької літери (що робиш), /do — з великої (що відбувається; зі знаком питання, якщо питаєш). Ігнорувати чуже /do заборонено.

Не можна використовувати в грі те, що дізнався поза нею (Discord, стрім) — це MG, за нього мут або Деморган.

Не можна відігравати на свою користь: «втратив свідомість» при затриманні, «документи вдома» тощо.

Повні правила сервера — на форумі: https://forum.quant5.com.ua/

